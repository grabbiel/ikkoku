#!/usr/bin/env python3
"""Developer-environment prerequisite checker (T-T01).

Reports, per capability, which tools are present, their versions and whether
they meet the requirement recorded in Tools/verification/prerequisites.json.
That file is the single source of the versions; the prerequisite table in
docs/guides/build-and-test.md is generated from it with --markdown.

Stdlib only. The checker runs version probes only: `--version`-style
commands and `importlib.metadata` lookups in the documented interpreters,
at the documented tool paths (some of which live under `.local/reverse/`).
It never reads `.local/` data, fixtures or game files, installs nothing,
writes nothing and uses no network.

Usage:
  python3 Tools/verification/doctor.py [--require public|optional|all|ID[,ID...]]...
      [--tool ID=PATH]... [--json | --markdown] [--verbose]

Every capability is always probed and reported. Exit status is 0 unless a
capability selected by --require is unmet (1); invalid arguments or an
invalid prerequisites file exit 2. --markdown prints the documentation
table from the prerequisites file without probing anything.
"""
import argparse
import hashlib
import json
import os
import platform
import posixpath
import re
import shutil
import subprocess
import sys

_HERE = os.path.dirname(os.path.abspath(__file__))
REPO_ROOT = os.path.abspath(os.path.join(_HERE, "..", ".."))
PREREQUISITES = os.path.join(_HERE, "prerequisites.json")
SCHEMA_VERSION = 1
TIERS = ("public", "optional")
PROBE_TIMEOUT = 60
OUTPUT_LIMIT = 4000
DETAIL_LIMIT = 200
DOC_PATH = "docs/guides/build-and-test.md"
DOC_BEGIN = ("<!-- BEGIN prerequisites: generated by `python3 Tools/verification/doctor.py "
             "--markdown` from Tools/verification/prerequisites.json; do not edit by hand -->")
DOC_END = "<!-- END prerequisites -->"

# Tool statuses. Only "ok" and "present" (found; no version is recorded to
# compare against) satisfy a capability.
MET_STATUSES = ("ok", "present")

# Exit code the package probe uses for "distribution not installed".
PACKAGE_MISSING_EXIT = 3
PACKAGE_SCRIPT = (
    "import sys\n"
    "import importlib.metadata as metadata\n"
    "try:\n"
    "    print(metadata.version(sys.argv[1]))\n"
    "except metadata.PackageNotFoundError:\n"
    "    sys.exit(%d)\n" % PACKAGE_MISSING_EXIT)

_NUMBERS = r"\d+(?:\.\d+)*"


class PrerequisiteError(Exception):
    """The prerequisites file or a command-line selection is invalid."""


# ---------------------------------------------------------------------------
# Version parsing (pure functions; tested against recorded sample outputs).
# Each parser returns (versions, detail): every version it found, in output
# order, plus a short human detail such as the build number or target.

def _search(pattern, text, flags=re.MULTILINE):
    match = re.search(pattern, text, flags)
    return match.group(1) if match else None


def parse_xcodebuild(output):
    version = _search(r"^Xcode (" + _NUMBERS + r")\s*$", output)
    build = _search(r"^Build version (\S+)", output)
    return ([version] if version else []), ("build " + build if version and build else None)


def parse_swift(output):
    # "Apple Swift version 6.3.3 (swiftlang-…)" from Xcode; open-source
    # toolchains print "Swift version 6.0.3 (swift-6.0.3-RELEASE)".
    version = _search(r"\bSwift version (" + _NUMBERS + r")", output)
    target = _search(r"^Target: (\S+)", output)
    return ([version] if version else []), ("target " + target if version and target else None)


def parse_metal(output):
    version = _search(r"\bmetal version (" + _NUMBERS + r")", output)
    target = _search(r"^Target: (\S+)", output)
    return ([version] if version else []), ("target " + target if version and target else None)


def parse_python(output):
    version = _search(r"^Python (\d+\.\d+(?:\.\d+)?(?:(?:a|b|rc)\d+)?\+?)\s*$", output)
    return ([version] if version else []), None


def parse_dotnet_sdks(output):
    # `dotnet --list-sdks`: one "10.0.100 [/usr/local/share/dotnet/sdk]" line
    # per installed SDK; a runtime-only install prints nothing.
    versions = re.findall(r"^(\d+\.\d+\.\d+(?:-[0-9A-Za-z.]+)?) \[[^\]]*\]\s*$", output, re.MULTILINE)
    return versions, ("installed SDKs: " + ", ".join(versions) if versions else None)


def parse_blender(output):
    version = _search(r"^Blender (\d+\.\d+(?:\.\d+)?)\b", output)
    build_hash = _search(r"^\s*build hash: (\S+)", output)
    return ([version] if version else []), ("build " + build_hash if version and build_hash else None)


def parse_ilspycmd(output):
    version = _search(r"^ilspycmd:\s*(\d+(?:\.\d+)+)", output)
    if version is None:
        version = _search(r"^\s*(\d+\.\d+\.\d+(?:\.\d+)?)\s*$", output)
    decompiler = _search(r"^ICSharpCode\.Decompiler:\s*(\S+)", output)
    return ([version] if version else []), ("decompiler " + decompiler if version and decompiler else None)


def parse_prlctl(output):
    version = _search(r"^prlctl version (" + _NUMBERS + r")", output)
    build = _search(r"^prlctl version " + _NUMBERS + r" \((\d+)\)", output)
    return ([version] if version else []), ("build " + build if version and build else None)


def parse_package(output):
    version = _search(r"^\s*(\d+(?:\.\d+)*[0-9A-Za-z.+_-]*)\s*$", output)
    return ([version] if version else []), None


PARSERS = {
    "xcodebuild": parse_xcodebuild,
    "swift": parse_swift,
    "metal": parse_metal,
    "python": parse_python,
    "dotnet-sdks": parse_dotnet_sdks,
    "blender": parse_blender,
    "ilspycmd": parse_ilspycmd,
    "prlctl": parse_prlctl,
    "package": parse_package,
}


def version_key(version):
    """(numeric components, is_prerelease) for '10.0.100-rc.2', '3.12.4', '1.23.0rc1'."""
    match = re.match(r"(" + _NUMBERS + r")(.*)$", version.strip())
    if not match:
        raise ValueError("not a version: %r" % version)
    numbers = tuple(int(part) for part in match.group(1).split("."))
    return numbers, bool(match.group(2).strip().strip("+"))


def _newest(versions):
    """The newest version; a release sorts after its own prereleases."""
    def order(version):
        numbers, prerelease = version_key(version)
        return numbers, not prerelease
    return max(versions, key=order)


def parse_requirement(text):
    """Requirement grammar: '>=V', 'V.*', '==V', 'unrecorded' or 'macos-arm64'."""
    if not isinstance(text, str):
        raise PrerequisiteError("requirement must be a string: %r" % (text,))
    if text in ("unrecorded", "macos-arm64"):
        return {"kind": text, "version": None, "text": text}
    for prefix, kind in ((">=", "minimum"), ("==", "exact")):
        if text.startswith(prefix):
            version = text[len(prefix):]
            break
    else:
        if not text.endswith(".*"):
            raise PrerequisiteError("unsupported requirement %r" % text)
        kind, version = "series", text[:-2]
    if not re.match(r"^" + _NUMBERS + r"$", version):
        raise PrerequisiteError("requirement %r needs a numeric version" % text)
    return {"kind": kind, "version": version, "text": text}


def _pad(numbers, length):
    return tuple(numbers) + (0,) * (length - len(numbers))


def satisfies(version, requirement):
    """Whether `version` meets a parsed requirement with a version."""
    numbers, prerelease = version_key(version)
    wanted = tuple(int(part) for part in requirement["version"].split("."))
    kind = requirement["kind"]
    if kind == "series":
        return numbers[:len(wanted)] == wanted
    length = max(len(numbers), len(wanted))
    have, want = _pad(numbers, length), _pad(wanted, length)
    if kind == "exact":
        return have == want and not prerelease
    if kind == "minimum":
        # A prerelease of exactly the minimum precedes that release.
        return have > want or (have == want and not prerelease)
    raise ValueError("requirement %r has no version to compare" % requirement["text"])


def display_requirement(text):
    """Human form of a requirement string for the text report."""
    return {"unrecorded": "any version (none recorded)",
            "macos-arm64": "macOS on Apple Silicon"}.get(text, text)


def _first_line(text):
    for line in text.splitlines():
        if line.strip():
            line = line.strip()
            return line if len(line) <= DETAIL_LIMIT else line[:DETAIL_LIMIT - 3] + "..."
    return None


def evaluate(tool, probe):
    """Turn one probe result into a tool record.

    `probe` is {"path", "argv", "returncode", "output", "error"}; a None path
    means no candidate resolved (absent). Pure: tested with sample outputs.
    """
    requirement = tool["requirementSpec"]
    record = {
        "id": tool["id"], "name": tool["name"], "requirement": requirement["text"],
        "status": None, "version": None, "detail": None,
        "path": probe.get("path"), "argv": probe.get("argv"),
        "exitCode": probe.get("returncode"), "output": probe.get("output"),
    }
    if probe.get("path") is None:
        record.update(status="absent", detail=probe.get("error"))
        return record
    if probe.get("error"):
        record.update(status="error", detail=probe["error"])
        return record
    output = probe.get("output") or ""
    if tool.get("probe") == "package" and probe.get("returncode") == PACKAGE_MISSING_EXIT:
        record.update(status="absent", detail="%s is not installed in %s" % (tool["distribution"], probe["path"]))
        return record
    if probe.get("returncode") != 0:
        record.update(status="error", detail=_first_line(output) or "exit status %s" % probe.get("returncode"))
        return record
    versions, detail = PARSERS[tool["parser"]](output)
    record["detail"] = detail
    if not versions:
        if tool["parser"] == "dotnet-sdks":
            record.update(status="absent", detail="dotnet runs but lists no installed SDK")
        elif requirement["kind"] == "unrecorded":
            record.update(status="present", detail=_first_line(output))
        else:
            record.update(status="unparsed", detail=_first_line(output) or "no output")
        return record
    if requirement["kind"] == "unrecorded":
        record.update(status="present", version=_newest(versions))
        return record
    meeting = [version for version in versions if satisfies(version, requirement)]
    if meeting:
        record.update(status="ok", version=_newest(meeting))
    else:
        record.update(status="mismatch", version=_newest(versions))
    return record


def evaluate_host(tool, host):
    """`host` is {"system", "machine", "macVersion", "appleSilicon"}."""
    record = {
        "id": tool["id"], "name": tool["name"], "requirement": tool["requirementSpec"]["text"],
        "status": None, "version": None, "detail": None, "path": None, "argv": None,
        "exitCode": None, "output": None,
    }
    system, machine = host.get("system") or "unknown", host.get("machine") or "unknown"
    if system == "Darwin" and (machine == "arm64" or host.get("appleSilicon")):
        record["status"] = "ok"
        record["version"] = host.get("macVersion") or None
        record["detail"] = ("macOS arm64" if machine == "arm64"
                            else "%s process on Apple Silicon (Rosetta)" % machine)
    else:
        record["status"] = "mismatch"
        record["detail"] = "%s %s" % ("macOS" if system == "Darwin" else system, machine)
    return record


# ---------------------------------------------------------------------------
# Prerequisites file.

def _relative_file(path, what):
    if not isinstance(path, str) or not path or os.path.isabs(path) or ".." in path.split("/"):
        raise PrerequisiteError("%s must be a repository-relative path: %r" % (what, path))
    if not os.path.isfile(os.path.join(REPO_ROOT, path)):
        raise PrerequisiteError("%s does not exist: %s" % (what, path))
    return path


def read_requirements_file(path):
    """Exact `name==version` pins from a pip requirements file."""
    pins = []
    with open(os.path.join(REPO_ROOT, path), encoding="utf-8") as handle:
        for number, line in enumerate(handle, 1):
            text = line.split("#", 1)[0].strip()
            if not text:
                continue
            match = re.match(r"^([A-Za-z0-9][A-Za-z0-9._-]*)==(" + _NUMBERS + r")$", text)
            if not match:
                raise PrerequisiteError("%s:%d: only exact name==version pins are supported" % (path, number))
            pins.append((match.group(1), match.group(2)))
    if not pins:
        raise PrerequisiteError("%s lists no packages" % path)
    return pins


def _check_tool_common(tool):
    for key in ("id", "name", "install"):
        if not isinstance(tool.get(key), str) or not tool[key]:
            raise PrerequisiteError("tool %r needs a nonempty %s" % (tool.get("id"), key))
    if not re.match(r"^[a-z0-9][a-z0-9-]*$", tool["id"]):
        raise PrerequisiteError("tool id %r must be lowercase words joined by '-'" % tool["id"])
    for key in ("statedIn", "observed"):
        if not isinstance(tool.get(key), list):
            raise PrerequisiteError("tool %s needs a %s list" % (tool["id"], key))
    for observed in tool["observed"]:
        if not isinstance(observed, str) or not observed:
            raise PrerequisiteError("tool %s has an empty observed entry" % tool["id"])
    for stated in tool["statedIn"]:
        if not isinstance(stated, dict) or not isinstance(stated.get("phrase"), str) or not stated["phrase"]:
            raise PrerequisiteError("tool %s has a statedIn entry without a phrase" % tool["id"])
        _relative_file(stated.get("path"), "statedIn path of %s" % tool["id"])


def load_prerequisites(path=PREREQUISITES):
    """Load, validate and normalize the prerequisites file.

    A `requirements` entry expands into one package tool per pin, so
    package versions stay stated once, in the requirements file.
    """
    try:
        with open(path, "rb") as handle:
            raw = handle.read()
        data = json.loads(raw.decode("utf-8"))
    except (OSError, ValueError) as error:
        raise PrerequisiteError("cannot read %s: %s" % (path, error))
    if not isinstance(data, dict) or data.get("schemaVersion") != SCHEMA_VERSION:
        raise PrerequisiteError("%s: schemaVersion must be %d" % (path, SCHEMA_VERSION))
    if not isinstance(data.get("reviewed"), str) or not re.match(r"^\d{4}-\d{2}-\d{2}$", data["reviewed"]):
        raise PrerequisiteError("%s: reviewed must be a YYYY-MM-DD date" % path)
    if not isinstance(data.get("tools"), list) or not isinstance(data.get("capabilities"), list):
        raise PrerequisiteError("%s: tools and capabilities must be lists" % path)
    if set(data.get("tiers", {})) != set(TIERS):
        raise PrerequisiteError("%s: tiers must describe exactly %s" % (path, ", ".join(TIERS)))

    tools, groups, taken = {}, {}, set()
    for entry in data["tools"]:
        if not isinstance(entry, dict):
            raise PrerequisiteError("each tool must be an object")
        tool = dict(entry)
        kind = tool.setdefault("probe", "command")
        if kind == "requirements":
            for key in ("id", "name", "label", "install", "interpreter"):
                if not isinstance(tool.get(key), str) or not tool[key]:
                    raise PrerequisiteError("requirements entry %r needs %s" % (tool.get("id"), key))
            if tool["id"] in taken:
                raise PrerequisiteError("duplicate tool id %s" % tool["id"])
            taken.add(tool["id"])
            source = _relative_file(tool.get("file"), "requirements file of %s" % tool["id"])
            members = []
            for name, version in read_requirements_file(source):
                member = {
                    "id": "%s:%s" % (tool["id"], name.lower()), "name": "%s (%s)" % (name, tool["label"]),
                    "probe": "package", "interpreter": tool["interpreter"], "distribution": name,
                    "requirement": "==" + version, "statedIn": [{"path": source, "phrase": name + "=={version}"}],
                    "observed": [], "install": tool["install"], "parser": "package",
                }
                members.append(member)
            groups[tool["id"]] = [member["id"] for member in members]
            new_tools = members
        else:
            _check_tool_common(tool)
            if kind == "command":
                candidates = tool.get("candidates")
                if (not isinstance(candidates, list) or not candidates
                        or not all(isinstance(item, str) and item for item in candidates)):
                    raise PrerequisiteError("tool %s needs candidate executables" % tool["id"])
                argv = tool.get("argv")
                if not isinstance(argv, list) or not argv or argv[0] != "{exe}" or not all(
                        isinstance(item, str) for item in argv):
                    raise PrerequisiteError("tool %s argv must start with {exe}" % tool["id"])
                if tool.get("parser") not in PARSERS or tool["parser"] == "package":
                    raise PrerequisiteError("tool %s has unknown parser %r" % (tool["id"], tool.get("parser")))
            elif kind == "package":
                if not isinstance(tool.get("distribution"), str) or not isinstance(tool.get("interpreter"), str):
                    raise PrerequisiteError("package tool %s needs distribution and interpreter" % tool["id"])
                tool["parser"] = "package"
            elif kind == "host":
                if tool.get("requirement") != "macos-arm64":
                    raise PrerequisiteError("host tool %s must require macos-arm64" % tool["id"])
            else:
                raise PrerequisiteError("tool %s has unknown probe %r" % (tool["id"], kind))
            new_tools = [tool]
        for item in new_tools:
            if item["id"] in taken:
                raise PrerequisiteError("duplicate tool id %s" % item["id"])
            taken.add(item["id"])
            spec = parse_requirement(item.get("requirement"))
            if (spec["kind"] == "macos-arm64") != (item["probe"] == "host"):
                raise PrerequisiteError("tool %s: macos-arm64 is only for the host probe" % item["id"])
            item["requirementSpec"] = spec
            tools[item["id"]] = item
    for tool in tools.values():
        if tool["probe"] == "package":
            interpreter = tools.get(tool["interpreter"])
            if interpreter is None or interpreter["probe"] != "command" or interpreter["parser"] != "python":
                raise PrerequisiteError("package tool %s needs a python command tool as interpreter" % tool["id"])
        for stated in tool["statedIn"]:
            if "{version}" in stated["phrase"] or "{major}" in stated["phrase"]:
                if tool["requirementSpec"]["version"] is None:
                    raise PrerequisiteError("tool %s states a version it does not record" % tool["id"])

    capabilities, seen = [], set()
    for entry in data["capabilities"]:
        if not isinstance(entry, dict):
            raise PrerequisiteError("each capability must be an object")
        capability = dict(entry)
        for key in ("id", "name", "exercisedBy"):
            if not isinstance(capability.get(key), str) or not capability[key]:
                raise PrerequisiteError("capability %r needs a nonempty %s" % (capability.get("id"), key))
        if capability["id"] in seen or capability["id"] in TIERS + ("all",):
            raise PrerequisiteError("capability id %s is duplicated or reserved" % capability["id"])
        seen.add(capability["id"])
        if capability.get("tier") not in TIERS:
            raise PrerequisiteError("capability %s has unknown tier %r" % (capability["id"], capability.get("tier")))
        _relative_file(capability.get("doc"), "doc of %s" % capability["id"])
        expanded = []
        for tool_id in capability.get("tools") or []:
            members = groups.get(tool_id, [tool_id])
            for member in members:
                if member not in tools:
                    raise PrerequisiteError("capability %s names unknown tool %s" % (capability["id"], member))
                if member not in expanded:
                    expanded.append(member)
        if not expanded:
            raise PrerequisiteError("capability %s lists no tools" % capability["id"])
        capability["toolIds"] = expanded
        capabilities.append(capability)
    return {
        "path": os.path.relpath(os.path.abspath(path), REPO_ROOT).replace(os.sep, "/"),
        "sha256": hashlib.sha256(raw).hexdigest(),
        "reviewed": data["reviewed"],
        "tiers": data["tiers"],
        "tools": tools,
        "capabilities": capabilities,
    }


def stated_phrase(tool, stated):
    """A statedIn phrase with {version} and {major} filled from the requirement."""
    version = tool["requirementSpec"]["version"] or ""
    return stated["phrase"].replace("{version}", version).replace("{major}", version.split(".")[0])


# ---------------------------------------------------------------------------
# Probing the real environment.

def default_resolver(candidate):
    """Resolve an executable: repository-relative or absolute path, else PATH."""
    if "/" in candidate:
        path = candidate if os.path.isabs(candidate) else os.path.join(REPO_ROOT, candidate)
        return path if os.path.isfile(path) and os.access(path, os.X_OK) else None
    return shutil.which(candidate)


def default_runner(argv, timeout=PROBE_TIMEOUT):
    """Run a probe; returns (returncode, combined output). May raise OSError/TimeoutExpired."""
    result = subprocess.run(argv, stdin=subprocess.DEVNULL, stdout=subprocess.PIPE,
                            stderr=subprocess.PIPE, cwd=REPO_ROOT, timeout=timeout, check=False)
    output = result.stdout.decode("utf-8", "replace")
    error = result.stderr.decode("utf-8", "replace")
    if error:
        output = output + ("\n" if output and not output.endswith("\n") else "") + error
    return result.returncode, output


def default_host():
    system, machine = platform.system(), platform.machine()
    apple_silicon = machine == "arm64"
    if system == "Darwin" and not apple_silicon:
        try:
            code, output = default_runner(["sysctl", "-n", "hw.optional.arm64"], timeout=10)
            apple_silicon = code == 0 and output.strip() == "1"
        except (OSError, subprocess.SubprocessError):
            apple_silicon = False
    return {"system": system, "machine": machine,
            "macVersion": platform.mac_ver()[0] if system == "Darwin" else "",
            "appleSilicon": apple_silicon}


def resolve_tool(tool, overrides, environ, resolver):
    """(path or None, explanation). `$VAR` candidates are used exclusively when set."""
    if tool["id"] in overrides:
        value = overrides[tool["id"]]
        path = resolver(value)
        return path, None if path else "--tool %s=%s is not an executable" % (tool["id"], value)
    tried = []
    for candidate in tool["candidates"]:
        if candidate.startswith("$"):
            value = environ.get(candidate[1:])
            if not value:
                tried.append(candidate + " (unset)")
                continue
            path = resolver(value)
            # The owning script uses the variable without a fallback.
            return path, None if path else "%s=%s is not an executable" % (candidate[1:], value)
        path = resolver(candidate)
        if path:
            return path, None
        tried.append(candidate)
    return None, "not found: " + ", ".join(tried)


def _bounded(text):
    return text if len(text) <= OUTPUT_LIMIT else text[:OUTPUT_LIMIT] + "\n[truncated]"


def probe_command(argv, path, runner):
    probe = {"path": path, "argv": argv, "returncode": None, "output": None, "error": None}
    try:
        code, output = runner(argv)
    except FileNotFoundError:
        probe.update(path=None, error="not found: " + argv[0])
    except subprocess.TimeoutExpired:
        probe["error"] = "timed out after %d s" % PROBE_TIMEOUT
    except (OSError, subprocess.SubprocessError) as error:
        probe["error"] = "could not run: %s" % error
    else:
        probe.update(returncode=code, output=_bounded(output))
    return probe


def check_environment(prerequisites, overrides=None, environ=None, resolver=default_resolver,
                      runner=default_runner, host=None):
    """Probe every tool once and evaluate every capability."""
    overrides = overrides or {}
    environ = os.environ if environ is None else environ
    tools = prerequisites["tools"]
    unknown = sorted(set(overrides) - set(tid for tid, tool in tools.items() if tool["probe"] == "command"))
    if unknown:
        raise PrerequisiteError("--tool names no command tool: %s" % ", ".join(unknown))
    records, resolved = {}, {}
    for tool_id, tool in tools.items():
        if tool["probe"] == "command":
            path, why = resolve_tool(tool, overrides, environ, resolver)
            resolved[tool_id] = path
            if path is None:
                probe = {"path": None, "argv": None, "returncode": None, "output": None, "error": why}
            else:
                argv = [path if item == "{exe}" else item for item in tool["argv"]]
                probe = probe_command(argv, path, runner)
            records[tool_id] = evaluate(tool, probe)
        elif tool["probe"] == "host":
            records[tool_id] = evaluate_host(tool, host if host is not None else default_host())
    for tool_id, tool in tools.items():
        if tool["probe"] != "package":
            continue
        interpreter = records[tool["interpreter"]]
        if interpreter["status"] not in MET_STATUSES + ("mismatch", "unparsed"):
            probe = {"path": None, "argv": None, "returncode": None, "output": None,
                     "error": "interpreter %s is %s" % (tool["interpreter"], interpreter["status"])}
        else:
            argv = [interpreter["path"], "-c", PACKAGE_SCRIPT, tool["distribution"]]
            probe = probe_command(argv, interpreter["path"], runner)
        records[tool_id] = evaluate(tool, probe)
        if interpreter["status"] == "mismatch" and records[tool_id]["status"] == "ok":
            records[tool_id]["detail"] = "installed, but the interpreter does not meet %s" % interpreter["requirement"]
    capabilities = []
    for capability in prerequisites["capabilities"]:
        unmet = [tid for tid in capability["toolIds"] if records[tid]["status"] not in MET_STATUSES]
        capabilities.append({"id": capability["id"], "tier": capability["tier"], "name": capability["name"],
                             "met": not unmet, "tools": list(capability["toolIds"]), "unmetTools": unmet,
                             "exercisedBy": capability["exercisedBy"], "doc": capability["doc"]})
    return {"tools": records, "capabilities": capabilities}


def select_capabilities(prerequisites, specs):
    """Expand --require values: tier names, 'all' or capability ids (comma lists allowed)."""
    ids = [capability["id"] for capability in prerequisites["capabilities"]]
    selected = []
    for spec in specs:
        for item in spec.split(","):
            item = item.strip()
            if not item:
                continue
            if item == "all":
                names = ids
            elif item in TIERS:
                names = [c["id"] for c in prerequisites["capabilities"] if c["tier"] == item]
            elif item in ids:
                names = [item]
            else:
                raise PrerequisiteError("unknown capability %r; choose from %s" % (
                    item, ", ".join(list(TIERS) + ["all"] + ids)))
            selected.extend(name for name in names if name not in selected)
    return selected


