def render_text(prerequisites, results, required, verbose=False):
    tools = prerequisites["tools"]
    lines = ["Ikkoku prerequisites from %s (reviewed %s)" % (prerequisites["path"], prerequisites["reviewed"]),
             "Statuses: ok / present (no recorded version) satisfy; mismatch, unparsed, error and absent do not.", ""]
    for capability in results["capabilities"]:
        lines.append("[%s] %s: %s -- %s" % (capability["tier"], capability["id"], capability["name"],
                                            "met" if capability["met"] else "UNMET"))
        for tool_id in capability["tools"]:
            record = results["tools"][tool_id]
            line = "  %-9s %-36s %-14s need %s" % (record["status"], record["name"], record["version"] or "-",
                                                   display_requirement(record["requirement"]))
            if record["detail"]:
                line += "  (%s)" % record["detail"]
            lines.append(line)
            if record["status"] not in MET_STATUSES:
                lines.append("            fix: %s" % tools[tool_id]["install"])
            if verbose and record["argv"]:
                if tools[tool_id]["probe"] == "package":
                    ran = '%s -c "importlib.metadata.version(%r)"' % (record["argv"][0], tools[tool_id]["distribution"])
                else:
                    ran = " ".join(record["argv"])
                lines.append("            ran: %s" % ran)
                for output_line in (record["output"] or "").splitlines():
                    lines.append("            | " + output_line)
        lines.append("")
    for tier in TIERS:
        tier_caps = [c for c in results["capabilities"] if c["tier"] == tier]
        lines.append("%s: %d/%d capabilities met" % (tier, sum(c["met"] for c in tier_caps), len(tier_caps)))
    if required:
        unmet = [c["id"] for c in results["capabilities"] if c["id"] in required and not c["met"]]
        if unmet:
            lines.append("--require: unmet %s (exit 1)" % ", ".join(unmet))
        else:
            lines.append("--require: all %d selected capabilities met" % len(required))
    else:
        lines.append("No --require given, so unmet capabilities do not change the exit status "
                     "(use --require public before building).")
    return "\n".join(lines) + "\n"


def _cell(text):
    return text.replace("|", "\\|").replace("\n", " ")


def _link(path, doc_dir):
    return "[%s](%s)" % (path, posixpath.relpath(path, doc_dir))


def _probe_text(tool, tools):
    if tool["probe"] == "host":
        return "Python `platform` (built in)"
    if tool["probe"] == "package":
        return "`importlib.metadata` via `%s`" % tools[tool["interpreter"]]["candidates"][0]
    first, rest = tool["candidates"][0], tool["candidates"][1:]
    command = "`%s`" % " ".join([first] + tool["argv"][1:])
    if rest:
        command += " (%s %s)" % ("default" if first.startswith("$") else "else",
                                 ", ".join("`%s`" % item for item in rest))
    return command


def render_markdown(prerequisites, doc_path=DOC_PATH):
    """The generated documentation block; deterministic and probe-free."""
    doc_dir = posixpath.dirname(doc_path)
    tools = prerequisites["tools"]
    lines = [DOC_BEGIN, "",
             "Recorded in %s, reviewed %s." % (_link(prerequisites["path"], doc_dir), prerequisites["reviewed"]),
             "`>=V` is a minimum, `V.*` a release series and `==V` an exact pin.",
             "*Unrecorded* means the repository documents no version, so only presence",
             "is checked. Observed versions are dated runs, not support claims.", "",
             "| Capability | Tier | Needs | Exercised by |", "| --- | --- | --- | --- |"]
    for capability in prerequisites["capabilities"]:
        see = "" if capability["doc"] == doc_path else "; see " + _link(capability["doc"], doc_dir)
        lines.append("| `%s`: %s | %s | %s | %s%s |" % (
            capability["id"], _cell(capability["name"]), capability["tier"],
            _cell(", ".join(tools[tid]["name"] for tid in capability["toolIds"])),
            _cell(capability["exercisedBy"]), see))
    lines += ["", "| Tool | Requirement | Probe | Stated in | Observed |", "| --- | --- | --- | --- | --- |"]
    for tool in tools.values():
        requirement = tool["requirementSpec"]["text"]
        requirement = {"unrecorded": "*unrecorded*", "macos-arm64": "macOS on Apple Silicon"}.get(
            requirement, "`%s`" % requirement)
        stated = ", ".join(sorted(set(_link(item["path"], doc_dir) for item in tool["statedIn"]))) or "-"
        observed = "; ".join(tool["observed"]) or "-"
        lines.append("| %s | %s | %s | %s | %s |" % (_cell(tool["name"]), requirement,
                                                    _cell(_probe_text(tool, tools)), stated, _cell(observed)))
    lines += ["", DOC_END]
    return "\n".join(lines) + "\n"


def extract_doc_block(text):
    """The generated block in a document, or None."""
    start = text.find(DOC_BEGIN)
    end = text.find(DOC_END, start + 1 if start >= 0 else 0)
    if start < 0 or end < 0:
        return None
    return text[start:end + len(DOC_END)] + "\n"


def json_report(prerequisites, results, required):
    unmet = [c["id"] for c in results["capabilities"] if c["id"] in required and not c["met"]]
    return {
        "schemaVersion": SCHEMA_VERSION,
        "prerequisites": {"path": prerequisites["path"], "sha256": prerequisites["sha256"],
                          "reviewed": prerequisites["reviewed"]},
        "checker": {"python": platform.python_version(), "platform": platform.platform()},
        "tools": results["tools"],
        "capabilities": results["capabilities"],
        "required": required,
        "unmetRequired": unmet,
        "exitCode": 1 if unmet else 0,
    }


def _parse_overrides(values):
    overrides = {}
    for value in values:
        tool_id, sep, path = value.partition("=")
        if not sep or not tool_id or not path:
            raise PrerequisiteError("--tool expects ID=PATH, got %r" % value)
        overrides[tool_id] = path
    return overrides


def main(argv=None, out=None, **probe_options):
    out = out or sys.stdout
    parser = argparse.ArgumentParser(description="Check the Ikkoku developer prerequisites (T-T01).")
    parser.add_argument("--require", action="append", default=[], metavar="CAPABILITIES",
                        help="public, optional, all or capability ids (comma-separated, repeatable); "
                             "exit 1 if any selected capability is unmet")
    parser.add_argument("--tool", action="append", default=[], metavar="ID=PATH",
                        help="use PATH for a command tool, e.g. reverse-python=python3.12")
    output = parser.add_mutually_exclusive_group()
    output.add_argument("--json", action="store_true", help="print a JSON report")
    output.add_argument("--markdown", action="store_true",
                        help="print the build-guide table from the prerequisites file (no probing)")
    parser.add_argument("--verbose", action="store_true", help="also print each probe command and its output")
    parser.add_argument("--prerequisites", default=PREREQUISITES, help=argparse.SUPPRESS)
    args = parser.parse_args(argv)
    try:
        prerequisites = load_prerequisites(args.prerequisites)
        if args.markdown:
            out.write(render_markdown(prerequisites))
            return 0
        required = select_capabilities(prerequisites, args.require)
        results = check_environment(prerequisites, overrides=_parse_overrides(args.tool), **probe_options)
    except PrerequisiteError as error:
        sys.stderr.write("doctor: %s\n" % error)
        return 2
    report = json_report(prerequisites, results, required)
    if args.json:
        out.write(json.dumps(report, indent=2) + "\n")
    else:
        out.write(render_text(prerequisites, results, required, verbose=args.verbose))
    return report["exitCode"]


if __name__ == "__main__":
    sys.exit(main())
